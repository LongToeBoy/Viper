(async () => {
  const original = clone(projectRoot);
  let passed = 0;
  const assert = (value, message) => { if (!value) throw new Error(message); passed++; };
  const picker = appearanceInspector.colorPicker;
  const background = document.getElementById('window-background');
  const choose = key => picker.palette.querySelector(`[data-key="${key}"]`).click();
  const apply = () => picker.dialog.querySelector('#color-apply').click();
  const cancel = () => picker.dialog.querySelector('#color-cancel').click();
  const bodyColor = () => getComputedStyle(surface.root.ownerDocument.body).backgroundColor;
  const byName = name => {
    const node = relativeLayout.nodes.get(project.components.find(component => component.name === name).id);
    return node.firstElementChild;
  };
  try {
    if (preview) togglePreview();
    selectWindow(); await appearanceInspector.choose('bootstrap.css');
    assert(background.value === '#ffffff' && background.dataset.color === '#ffffff', 'Background button shows the effective theme background');
    assert(background.textContent === 'Theme background', 'Background button explains that CSS owns the current color');
    const before = JSON.stringify(project.window);
    background.click();
    assert(picker.dialog.open && picker.apply.textContent === 'Apply', 'Color dialog has an explicit Apply button');
    assert(picker.palette.querySelector('[data-key="primary"]') && picker.palette.querySelector('[data-key="indigo"]'), 'Bootstrap named palette colors are selectable');
    choose('primary');
    const primary = picker.palette.querySelector('[data-key="primary"]'); primary.focus();
    primary.dispatchEvent(new KeyboardEvent('keydown', {key:'ArrowRight', bubbles:true, cancelable:true}));
    assert(ViperThemeColors.key(picker.draft.value) === 'secondary', 'Arrow keys select palette colors without tabbing through every swatch');
    choose('primary');
    assert(picker.preview.dataset.color === '#0d6efd', 'Palette selection previews the actual selected color');
    assert(JSON.stringify(project.window) === before && bodyColor() === 'rgb(255, 255, 255)', 'Palette selection remains a draft before Apply');
    cancel();
    assert(!picker.dialog.open && JSON.stringify(project.window) === before, 'Cancel leaves project colors unchanged');
    background.click(); choose('primary'); apply();
    assert(!picker.dialog.open && project.window.background_theme_color === 'primary', 'Apply stores a theme color role');
    assert(!project.window.use_theme_background && !document.getElementById('window-theme-background').checked, 'Choosing a background automatically overrides the theme background');
    assert(bodyColor() === 'rgb(13, 110, 253)' && background.value === '#0d6efd', 'Applied color updates both window and button');
    assert(background.textContent === 'Primary', 'Button displays the selected palette name');
    await appearanceInspector.choose('milligram.css');
    assert(project.window.background_theme_color === 'primary' && bodyColor() === 'rgb(155, 77, 202)', 'A theme-linked background follows the next theme primary color');
    assert(background.value === '#9b4dca', 'Background button follows the effective color across theme changes');
    background.click();
    assert(picker.palette.querySelector('[data-key="primary"]').getAttribute('aria-pressed') === 'true', 'Reopening highlights the selected named color');
    assert(picker.palette.children.length >= 7, 'Stylesheets without CSS variables still have a derived palette');
    cancel();
    background.click(); picker.setCustom('#123456'); apply();
    assert(bodyColor() === 'rgb(18, 52, 86)' && !project.window.background_theme_color, 'Custom background applies without a theme checkbox step');
    await appearanceInspector.choose('bootstrap.css');
    assert(bodyColor() === 'rgb(18, 52, 86)' && background.value === '#123456', 'Custom colors stay fixed across themes');
    background.click();
    picker.custom.value = 'not-a-color'; picker.custom.dispatchEvent(new Event('input'));
    assert(picker.apply.disabled && picker.error.textContent, 'Invalid custom colors cannot be applied');
    picker.setCustom('#aabbcc');
    assert(!picker.apply.disabled && picker.preview.dataset.color === '#aabbcc', 'Valid custom values restore Apply and update preview');
    picker.channels[0].number.value = '42'; picker.channels[0].number.dispatchEvent(new Event('input'));
    assert(picker.preview.dataset.color === '#2abbcc', 'RGB adjustments update the draft color');
    cancel();
    assert(project.window.background_color === '#123456', 'Cancelling RGB edits preserves the saved background');
    background.click(); picker.defaultButton.click(); apply();
    assert(project.window.use_theme_background && bodyColor() === 'rgb(255, 255, 255)', 'Use theme background restores the theme and displayed swatch');
    selectComponent(project.components[0].id);
    const button = project.components[0], originalSource = JSON.stringify(projectRoot.event_code);
    appearanceInspector.pickers.get('background_color').click(); choose('primary'); apply();
    assert(ViperThemeColors.key(button.style_overrides.background_color) === 'primary', 'Component colors use the same named palette');
    appearanceInspector.pickers.get('text_color').click(); choose('danger'); apply();
    assert(getComputedStyle(byName(button.name)).color === 'rgb(220, 53, 69)', 'Theme palette also works for text colors');
    await sync(); const saved = (await viperHost.request('bootstrap')).project;
    replaceProject(saved); selectComponent(project.components[0].id);
    await appearanceInspector.choose('milligram.css');
    assert(getComputedStyle(byName(button.name)).backgroundColor === 'rgb(155, 77, 202)', 'Named component colors survive save/reload and theme switching');
    assert(getComputedStyle(byName(button.name)).color === 'rgb(220, 53, 69)', 'Unavailable roles keep their saved fallback color');
    assert(JSON.stringify(projectRoot.event_code) === originalSource && project.components[0].name === button.name, 'Palette choices preserve control references and Python source');
    appearanceInspector.pickers.get('background_color').click(); picker.defaultButton.click(); apply();
    assert(!Object.hasOwn(project.components[0].style_overrides, 'background_color'), 'Use theme color clears an explicit component override');
    projectRoot.themes['brand.css'] = {name:'Brand', css:':root{--brand-primary:#e04080;--brand-accent:#008899;--brand-background:#fafafa} body{background:linear-gradient(red,blue) var(--brand-background)} button{background:var(--brand-primary)}'};
    await appearanceInspector.choose('brand.css'); selectWindow(); background.click();
    assert(picker.palette.querySelector('[data-key="brand-accent"]'), 'Imported CSS variable colors appear in the palette');
    choose('primary'); apply();
    assert(bodyColor() === 'rgb(224, 64, 128)' && background.value === '#e04080', 'Custom framework prefixes resolve primary roles');
    assert(getComputedStyle(surface.root.ownerDocument.body).backgroundImage === 'none', 'Explicit backgrounds override theme gradients');
    background.click(); picker.defaultButton.click(); apply();
    assert(getComputedStyle(surface.root.ownerDocument.body).backgroundImage.includes('gradient'), 'Returning to the theme background restores its gradient');
    project.window.use_theme_background = false;
    project.window.background_theme_color = 'brand-accent'; project.window.background_color = '#008899'; render();
    await appearanceInspector.choose('milligram.css');
    assert(bodyColor() === 'rgb(0, 136, 153)' && background.textContent.includes('saved color'), 'Missing palette colors keep their saved value and label');
    await appearanceInspector.choose('');
    assert(surface.root === canvas && background.value === '#008899', 'Theme color fallbacks work with the unthemed renderer');
    return {passed};
  } catch (error) { return {passed, error:error.stack || error.message}; }
  finally { if (picker.dialog.open) picker.dialog.close(); replaceProject(original); await sync(); }
})()
